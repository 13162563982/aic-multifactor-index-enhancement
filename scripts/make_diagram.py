def make_recovery_figure() -> None:
    fig, ax = plt.subplots(figsize=(12, 4.7), dpi=200)
    ax.set_xlim(0, 120)
    ax.set_ylim(0, 50)
    ax.axis("off")

    ax.text(60, 47.2, "Run state machine, crash recovery and escalation", ha="center", fontsize=13, fontweight="bold", color=INK)
    ax.text(
        60,
        44.3,
        "A crash can happen before or after a stage artifact is written. Resume re-checks the persisted input hash: completed work is skipped, the affected stage re-runs, and artifact hashes stay identical.",
        ha="center",
        fontsize=7.1,
        color=MUTED,
    )

    def mini_box(x, y, w, h, label, kind="code", fontsize=7.0):
        face, edge = COLORS[kind]
        rounded(ax, x, y, w, h, face, edge)
        ax.text(x + w / 2, y + h / 2, label, ha="center", va="center", fontsize=fontsize, fontweight="bold", color=INK)
        return (x, y, w, h)

    def chain(boxes, y, h, *, color=ARROW, ls="-"):
        for left, right in zip(boxes, boxes[1:]):
            arrow(ax, (left[0] + left[2], y + h / 2), (right[0], y + h / 2), color=color, ls=ls)

    # lane 1: normal path
    ax.text(4.0, 38.4, "NORMAL PATH", fontsize=6.8, fontweight="bold", color=MUTED)
    y1, h1 = 29.5, 7.6
    b1 = [
        mini_box(8, y1, 19, h1, "pending", "control"),
        mini_box(31, y1, 19, h1, "running", "control"),
        mini_box(54, y1, 22, h1, "awaiting approval", "human"),
        mini_box(80, y1, 19, h1, "completed", "control"),
    ]
    chain(b1, y1, h1)

    # lane 2: crash recovery
    ax.text(4.0, 26.6, "CRASH RECOVERY  (evidence/resume/)", fontsize=6.8, fontweight="bold", color="#dc2626")
    y2, h2 = 17.8, 7.4
    b2 = [
        mini_box(8, y2, 17.5, h2, "crash_after /\ncrash_before", "human", 6.5),
        mini_box(29.5, y2, 17.5, h2, "resume <run>", "code", 6.8),
        mini_box(51, y2, 19.5, h2, "skip stages with\nmatching hash", "code", 6.4),
        mini_box(74.5, y2, 18.5, h2, "re-run dirty\nstage", "code", 6.6),
        mini_box(97, y2, 18.5, h2, "artifact hash\nidentical", "monitor", 6.4),
    ]
    chain(b2, y2, h2, color="#dc2626", ls=(0, (4, 2)))

    # lane 3: pause and escalation
    ax.text(4.0, 14.6, "PAUSE & ESCALATION", fontsize=6.8, fontweight="bold", color=MUTED)
    y3, h3 = 5.8, 7.4
    b3 = [
        mini_box(8, y3, 20, h3, "budget exhausted\n(paused)", "human", 6.6),
        mini_box(33, y3, 20, h3, "raise limit →\nresume", "code", 6.6),
        mini_box(63, y3, 20, h3, "blocked / failed\n(escalation)", "human", 6.6),
        mini_box(88, y3, 20, h3, "human fixes input\n→ resume", "code", 6.6),
    ]
    chain(b3, y3, h3)

    ax.text(
        4.0,
        2.2,
        "Resume is stage-level, not run-level. Exit codes: 0 completed · 3 blocked/failed · 4 awaiting approval · 5 budget exhausted. Escalation artifacts name the failed stage, attempts and the human action required.",
        fontsize=6.6,
        color=INK,
    )

    fig.savefig(DOCS / "recovery_state.png", bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"wrote {DOCS / 'recovery_state.png'}")


if __name__ == "__main__":
    main()
