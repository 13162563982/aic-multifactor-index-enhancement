"""Generate the annotated architecture diagrams for the design note.

Outputs (committed):
    docs/architecture.png   high-resolution annotated workflow diagram
    docs/architecture.svg   vector version of the same figure
    docs/recovery_state.png run-state / recovery state machine

The diagram is deliberately generated by code so that it can be regenerated after
the workflow changes; it is not a hand-drawn picture.
"""

from __future__ import annotations

import textwrap
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Circle, FancyArrowPatch, FancyBboxPatch, Rectangle

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"

COLORS = {
    "code": ("#dbeafe", "#2563eb"),
    "agent": ("#fef3c7", "#d97706"),
    "human": ("#fee2e2", "#dc2626"),
    "control": ("#e5e7eb", "#374151"),
    "monitor": ("#dcfce7", "#16a34a"),
    "inset": ("#f8fafc", "#94a3b8"),
}
INK = "#1f2937"
MUTED = "#6b7280"
ARROW = "#475569"


def rounded(ax, x, y, w, h, face, edge, lw=1.2, radius=0.9, z=2):
    patch = FancyBboxPatch(
        (x, y),
        w,
        h,
        boxstyle=f"round,pad=0.02,rounding_size={radius}",
        linewidth=lw,
        edgecolor=edge,
        facecolor=face,
        zorder=z,
    )
    ax.add_patch(patch)
    return patch


def arrow(ax, start, end, *, style="-|>", lw=1.5, color=ARROW, ls="-", rad=0.0, z=3):
    ax.add_patch(
        FancyArrowPatch(
            start,
            end,
            arrowstyle=style,
            mutation_scale=12,
            linewidth=lw,
            color=color,
            linestyle=ls,
            connectionstyle=f"arc3,rad={rad}",
            shrinkA=2,
            shrinkB=2,
            zorder=z,
        )
    )


def stage_box(ax, x, y, w, h, num, title, kind, subtitle, artifacts):
    face, edge = COLORS[kind]
    rounded(ax, x, y, w, h, face, edge)
    ax.add_patch(Circle((x + 1.6, y + h - 1.7), 1.25, facecolor=edge, edgecolor="white", linewidth=1.0, zorder=4))
    ax.text(x + 1.6, y + h - 1.7, str(num), ha="center", va="center", color="white", fontsize=8.2, fontweight="bold", zorder=5)
    ax.text(x + 3.4, y + h - 1.9, title, ha="left", va="center", fontsize=10.2, fontweight="bold", color=INK, zorder=4)
    ax.text(x + 1.2, y + h - 5.2, subtitle, ha="left", va="top", fontsize=7.4, color=MUTED, zorder=4)
    ax.text(
        x + 1.2,
        y + 2.0,
        textwrap.fill(artifacts, width=44),
        ha="left",
        va="bottom",
        fontsize=6.7,
        color=INK,
        zorder=4,
    )


