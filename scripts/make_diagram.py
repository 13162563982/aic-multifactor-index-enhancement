        (7, 1, 1, "Robustness", "code", "subperiods · placebo · bias stress · DSR", "robustness.json · checks"),
        (8, 0, 1, "Risk critique", "agent", "Devil's-advocate agent (advisory)", "critique.md"),
        (9, 0, 2, "Portfolio", "code", "industry-neutral TE-constrained optimizer", "weights · orders · risk_report"),
        (10, 1, 2, "Independent verification", "code", "separate code path · PASS / FAIL", "verification.json · verifier_note.md"),
        (11, 2, 2, "Research note", "agent", "Report-writer agent · verified numbers only", "research_note.md · charts"),
