    ax.text(37.6, 55.5, "schedules · checkpoints · retries · gates", rotation=90, fontsize=7.2, color=MUTED, ha="center", va="center")
    ax.plot([36.9, 36.9], [19.0, 92.0], linestyle=(0, (2, 2)), linewidth=1.0, color="#9ca3af", zorder=1)

